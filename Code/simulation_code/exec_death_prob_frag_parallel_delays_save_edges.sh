#!/bin/bash

# Code to execute simulations with different log-normal distributions for several cluster
# generations (selecting one cluster after fragmentation to continue growing), across a
# range of death probabilities, running everything in parallel.
#
# This script requires a file created by causes_of_asynchrony_1oct2024.R with the parameters
# of the doubling time distributions for the simulations (same csv format used by
# exec_sim_frag_clust_from_file_params.sh).
#
# For every combination of (death probability) x (row in the csv file), a simulation is run
# with sim_frag_clust_death_prob_16sep2026.py. Outputs are organized as:
#   prob_00/test_${var_level}_var_${delay_level}_diff
#   prob_05/test_${var_level}_var_${delay_level}_diff
#   prob_10/test_${var_level}_var_${delay_level}_diff
#   ...
#
# Inputs:
#   -n: Number of simulations to be executed for each (death probability, csv row) combination
#   -g: Number of cluster generations to be simulated
#   -e: Edge degree threshold value for fragmentation
#   -c: Cluster to keep after fragmentation. Options: random, parent, propagule
#   -i: Input file, csv file generated by causes_of_asynchrony_1oct2024.R with the information
#       of the doubling time distributions
#   -p: Minimum death probability (0.0 to 1.0)
#   -P: Maximum death probability (0.0 to 1.0)
#   -s: Step size for death probability increments
#   -t: Number of threads/parallel processes to use

while getopts "n:g:e:c:i:p:P:s:t:" option
do
case "${option}"
in
n) sim_number=${OPTARG};;
g) generations=${OPTARG};;
e) edge_degree_threshold=${OPTARG};;
c) cluster_to_keep=${OPTARG};;
i) input_file=${OPTARG};;
p) min_death_prob=${OPTARG};;
P) max_death_prob=${OPTARG};;
s) death_prob_step=${OPTARG};;
t) num_threads=${OPTARG};;
*) echo "Invalid option or missing option argument for -$OPTARG" >&2; exit 1;;
esac
done

# Check if required arguments are provided
if [ -z "$sim_number" ] || [ -z "$generations" ] || [ -z "$edge_degree_threshold" ] || [ -z "$cluster_to_keep" ] || [ -z "$input_file" ] || [ -z "$min_death_prob" ] || [ -z "$max_death_prob" ] || [ -z "$death_prob_step" ] || [ -z "$num_threads" ]; then
    echo "Error: Missing required arguments!"
    echo "Usage: $0 -n <number_of_simulations> -g <generations> -e <edge_degree_threshold> -c <cluster_to_keep> -i <input_file> -p <min_death_prob> -P <max_death_prob> -s <death_prob_step> -t <number_of_threads>"
    echo ""
    echo "Example: $0 -n 100 -g 30 -e 4 -c random -i causes_of_asynchrony_params.csv -p 0.0 -P 0.3 -s 0.05 -t 4"
    exit 1
fi

# Check if the CSV file exists
if [ ! -f ${input_file} ]; then
    echo "Error: CSV file not found!"
    exit 1
fi

echo "Starting simulations with parameters:"
echo "Number of simulations per combination: ${sim_number}"
echo "Number of generations: ${generations}"
echo "Edge degree threshold: ${edge_degree_threshold}"
echo "Cluster to keep: ${cluster_to_keep}"
echo "Input parameters file: ${input_file}"
echo "Death probability range: ${min_death_prob} to ${max_death_prob} (step: ${death_prob_step})"
echo "Number of parallel threads: ${num_threads}"
echo "========================================"

# Function to execute a single simulation for one death probability and one row of the csv file
run_simulation() {
    local death_prob=$1
    local csv_line=$2
    local sim_number=$3
    local generations=$4
    local edge_degree_threshold=$5
    local cluster_to_keep=$6

    # Parse the csv row the same way exec_sim_frag_clust_from_file_params.sh does
    IFS=',' read -r delay_level var_level col3 col4 log_mean1 log_std1 col7 col8 log_mean2 log_std2 col11 <<< "${csv_line}"

    # Format death probability for the folder name using printf for consistent formatting
    # This turns 0.0 -> prob_00, 0.05 -> prob_05, 0.1 -> prob_10, 0.3 -> prob_30, etc.
    local death_prob_formatted=$(printf "%.2f" "$death_prob")
    local death_prob_suffix=${death_prob_formatted#*.}
    local prob_dir="prob_${death_prob_suffix}"

    mkdir -p "${prob_dir}"

    local output_dir="${prob_dir}/test_${var_level}_var_${delay_level}_diff"

    # Construct the command
    cmd="sim_frag_clust_death_prob_save_edges_order_6oct2026.py -n ${sim_number} -o ${output_dir} -g ${generations} -e ${edge_degree_threshold} -i ${log_mean1},${log_std1} -j ${log_mean2},${log_std2} -c ${cluster_to_keep} -p ${death_prob}"

    # Execute the command
    echo "Executing: $cmd"
    eval $cmd

    # Check if the command was successful
    if [ $? -eq 0 ]; then
        echo "Command executed successfully for death_prob=${death_prob}, var_level=${var_level}, delay_level=${delay_level}"
    else
        echo "Error: Command failed for death_prob=${death_prob}, var_level=${var_level}, delay_level=${delay_level}"
        return 1
    fi
    echo "----------------------------------------"
}

# Export the function and variables so they're available to parallel processes
export -f run_simulation
export sim_number
export generations
export edge_degree_threshold
export cluster_to_keep

# Generate death probability values and create a temporary file
death_prob_file=$(mktemp)

# Use bc for floating point arithmetic to generate the range
current_prob=$min_death_prob
while (( $(echo "$current_prob <= $max_death_prob" | bc -l) )); do
    echo "$current_prob" >> "$death_prob_file"
    current_prob=$(echo "$current_prob + $death_prob_step" | bc -l)
done

# Save the csv rows (without header) into a temporary file
csv_rows_file=$(mktemp)
tail -n +2 "${input_file}" > "${csv_rows_file}"

# Count how many death probabilities and csv rows we'll test
num_death_probs=$(wc -l < "$death_prob_file")
num_csv_rows=$(wc -l < "$csv_rows_file")
echo "Testing ${num_death_probs} different death probabilities across ${num_csv_rows} parameter combinations..."
echo "Total simulations to run: $((num_death_probs * num_csv_rows))"
echo ""

# Use GNU parallel for execution. Combining two input sources (death probabilities and csv
# rows) makes parallel run every combination of the two (a cartesian product).
echo "Using GNU parallel for execution..."
parallel -j ${num_threads} run_simulation {1} {2} ${sim_number} ${generations} ${edge_degree_threshold} ${cluster_to_keep} :::: ${death_prob_file} :::: ${csv_rows_file}

# Check if parallel command was successful
if [ $? -eq 0 ]; then
    echo ""
    echo "All simulations completed successfully!"
    echo "Output directories created: prob_00, prob_05, prob_10, etc., each containing test_<var_level>_var_<delay_level>_diff folders"
else
    echo ""
    echo "Some simulations may have failed. Check the output above for details."
fi

# Clean up temporary files
rm ${death_prob_file} ${csv_rows_file}

echo "========================================"
echo "Script execution completed."